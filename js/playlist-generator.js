// Playlist Generator with AI recommendations
class PlaylistGenerator {
    constructor() {
        this.playlists = [];
    }

    async createPlaylistByMood(songs, mood, name = null) {
        const filteredSongs = moodAnalyzer.generatePlaylistByMood(songs, mood);
        
        const playlist = {
            id: `playlist-${Date.now()}`,
            name: name || `${mood.charAt(0).toUpperCase() + mood.slice(1)} Vibes`,
            mood: mood,
            songs: filteredSongs.map(s => s.id),
            createdAt: Date.now(),
            autoGenerated: true,
            totalDuration: filteredSongs.reduce((sum, s) => sum + s.duration, 0)
        };

        await fileManager.savePlaylist(playlist);
        this.playlists.push(playlist);
        return playlist;
    }

    async createSmartPlaylist(songs, name = 'Smart Playlist') {
        const moods = moodAnalyzer.getTimeBasedMoodRecommendation();
        const smartSongs = moodAnalyzer.generateMixedPlaylist(songs, moods);

        const playlist = {
            id: `playlist-${Date.now()}`,
            name: name,
            mood: moods.join('+'),
            songs: smartSongs.map(s => s.id),
            createdAt: Date.now(),
            autoGenerated: true,
            totalDuration: smartSongs.reduce((sum, s) => sum + s.duration, 0)
        };

        await fileManager.savePlaylist(playlist);
        this.playlists.push(playlist);
        return playlist;
    }

    async createCustomPlaylist(songs, name, selectedSongIds) {
        const selectedSongs = songs.filter(s => selectedSongIds.includes(s.id));

        const playlist = {
            id: `playlist-${Date.now()}`,
            name: name,
            mood: 'custom',
            songs: selectedSongIds,
            createdAt: Date.now(),
            autoGenerated: false,
            totalDuration: selectedSongs.reduce((sum, s) => sum + s.duration, 0)
        };

        await fileManager.savePlaylist(playlist);
        this.playlists.push(playlist);
        return playlist;
    }

    getPlaylistStats(playlist, songs) {
        const playlistSongs = songs.filter(s => playlist.songs.includes(s.id));
        const moods = {};

        playlistSongs.forEach(song => {
            moods[song.mood] = (moods[song.mood] || 0) + 1;
        });

        return {
            songCount: playlistSongs.length,
            duration: playlist.totalDuration,
            averageDuration: Math.round(playlist.totalDuration / playlistSongs.length),
            moodDistribution: moods
        };
    }

    async deletePlaylist(playlistId) {
        this.playlists = this.playlists.filter(p => p.id !== playlistId);
    }

    getSortedPlaylists() {
        return [...this.playlists].sort((a, b) => b.createdAt - a.createdAt);
    }
}

const playlistGenerator = new PlaylistGenerator();
